"""Host large project-generated outputs in a private Hugging Face dataset repository.

The local disk is nearly full. This script moves selected local-only outputs that
the project itself generated (not third-party scans, captures or corpora) to a
private Hugging Face dataset repository, verifies every file against the Hub, and
only then can remove the verified local copies. Third-party payloads stay local:
their rights are unresolved, and Hugging Face requires uploaders to hold rights
to what they upload, including in private repositories.

Run from the repository root after logging in with
`python -m huggingface_hub.cli.hf auth login`:

    python experiments/2026-10-06-research-program/hf_host.py plan
    python experiments/2026-10-06-research-program/hf_host.py upload --repo NAMESPACE/indus-research-data
    python experiments/2026-10-06-research-program/hf_host.py verify --repo NAMESPACE/indus-research-data
    python experiments/2026-10-06-research-program/hf_host.py free-local --repo NAMESPACE/indus-research-data
    python experiments/2026-10-06-research-program/hf_host.py verify-remote --repo NAMESPACE/indus-research-data
    python experiments/2026-10-06-research-program/hf_host.py restore --repo NAMESPACE/indus-research-data
    python experiments/2026-10-06-research-program/hf_host.py publish-card --repo NAMESPACE/indus-research-data

`verify` checks local copies against the Hub, so it finds nothing to check once
`free-local` has removed them; `verify-remote` checks every manifest entry against
the size and SHA-256 the Hub reports, without downloading.
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "experiments/2026-10-06-research-program/hf-hosting-manifest.json"

# Project-generated outputs only. Each set is a directory relative to the repository root.
SETS = {
    "restoration-predictions": {
        "path": "data/raw/2026-10-06-modern-restoration/main",
        "note": "Package A per-fold predictions, counts and model checkpoints (derived from the local corpus export; private).",
    },
    "restoration-frozen-model": {
        "path": "data/raw/2026-10-06-modern-restoration/frozen-model",
        "note": "Weights and counts of the frozen restoration ensemble (private).",
    },
}

# Large project-generated files kept out of Git and backed up to the Hub without removing the local copy.
BACKUP_FILES = {
    "helsinki1979-provisional-occurrences": "experiments/2026-10-07-helsinki1979-digitization/runs/2026-10-07-full-v1/occurrences.jsonl",
    "helsinki1979-provisional-ledger-import": "experiments/2026-10-07-helsinki1979-digitization/integration/2026-10-07-v1/ledger-import.jsonl",
    "helsinki1979-repair-v1-frame": "experiments/2026-10-07-helsinki1979-digitization/repair/2026-10-07-v1/frame.json",
    "helsinki1979-repair-v2-frame": "experiments/2026-10-07-helsinki1979-digitization/repair/2026-10-07-v2/frame.json",
    "helsinki1979-v3-frame": "experiments/2026-10-07-helsinki1979-digitization/repair/2026-10-08-v3/frame.json",
    "helsinki1979-v3-full-proposals": "data/raw/2026-10-07-helsinki1979-digitization/2026-10-08-v3/full-v2/proposals.jsonl",
}


def files_of(rel):
    base = ROOT / rel
    return sorted(p for p in base.rglob("*") if p.is_file())


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def git_blob_sha1(path):
    data = path.read_bytes()
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def cmd_plan(_):
    total = 0
    for name, spec in SETS.items():
        fs = files_of(spec["path"])
        size = sum(p.stat().st_size for p in fs)
        total += size
        print(f"{name}: {spec['path']} - {len(fs)} files, {size / 1e9:.2f} GB")
    print(f"total: {total / 1e9:.2f} GB")


def api():
    from huggingface_hub import HfApi
    return HfApi()


def cmd_upload(args):
    hub = api()
    hub.create_repo(args.repo, repo_type="dataset", private=True, exist_ok=True)
    info = hub.repo_info(args.repo, repo_type="dataset")
    if not getattr(info, "private", False):
        sys.exit(f"{args.repo} is not private; refusing to upload")
    if not hub.file_exists(args.repo, "README.md", repo_type="dataset"):
        card = ROOT / "data/raw/2026-10-06-research-program/hf-dataset-card.md"
        card.parent.mkdir(parents=True, exist_ok=True)
        card.write_text(
            "# Indus research project: private hosted outputs\n\n"
            "Private storage for large outputs generated by the Indus script research repository "
            "(the GitHub repository k-sandhu/indus-valley-script). Paths mirror the repository. "
            "No third-party scans, captures or corpora are stored here. Not for public release.\n",
            encoding="utf-8",
        )
        hub.upload_file(path_or_fileobj=str(card), path_in_repo="README.md", repo_id=args.repo,
                        repo_type="dataset", commit_message="Describe the private hosted outputs")
    for name, spec in SETS.items():
        hub.upload_folder(folder_path=str(ROOT / spec["path"]), path_in_repo=spec["path"], repo_id=args.repo,
                          repo_type="dataset", commit_message=f"Host {name}: {spec['path']}")
        print(f"uploaded {spec['path']}")


def remote_index(hub, repo, rel):
    index = {}
    for item in hub.list_repo_tree(repo, path_in_repo=rel, recursive=True, expand=True, repo_type="dataset"):
        if getattr(item, "type", None) == "directory" or not hasattr(item, "size"):
            continue
        lfs = getattr(item, "lfs", None)
        index[item.path] = {
            "size": item.size,
            "sha256": (lfs.get("sha256") if isinstance(lfs, dict) else getattr(lfs, "sha256", None)) if lfs else None,
            "blob_id": getattr(item, "blob_id", None),
        }
    return index


def verify(repo):
    hub = api()
    records, failures = [], []
    for name, spec in SETS.items():
        remote = remote_index(hub, repo, spec["path"])
        for p in files_of(spec["path"]):
            rel = p.relative_to(ROOT).as_posix()
            r = remote.get(rel)
            local_sha = sha256(p)
            ok = bool(r) and r["size"] == p.stat().st_size and (
                (r["sha256"] and r["sha256"] == local_sha) or (not r["sha256"] and r["blob_id"] == git_blob_sha1(p)))
            records.append({"set": name, "path": rel, "bytes": p.stat().st_size, "sha256": local_sha, "verified": ok})
            if not ok:
                failures.append(rel)
    return records, failures


def cmd_verify(args):
    records, failures = verify(args.repo)
    print(f"verified {len(records) - len(failures)} of {len(records)} local files")
    if not records:
        print("no local copies exist; use verify-remote to check the Hub against the manifest")
    for f in failures[:20]:
        print("NOT VERIFIED:", f)
    return records, failures


def cmd_verify_remote(args):
    """Compare every manifest entry with the size and SHA-256 the Hub reports.

    Large files are stored with LFS and the Hub reports their SHA-256 directly. Small files are
    plain Git blobs, for which the Hub reports only a Git SHA-1, so those are downloaded to a
    temporary folder and hashed."""
    import tempfile
    from huggingface_hub import hf_hub_download
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    entries = manifest.get("files", []) + manifest.get("backed_up_files_kept_locally", [])
    hub = api()
    remote = {}
    for top in sorted({e["path"].split("/")[0] for e in entries}):
        remote.update(remote_index(hub, args.repo, top))
    failures, downloaded = [], 0
    with tempfile.TemporaryDirectory() as tmp:
        for e in entries:
            r = remote.get(e["path"])
            if not r or r["size"] != e["bytes"]:
                failures.append(e["path"])
            elif r["sha256"]:
                if r["sha256"] != e["sha256"]:
                    failures.append(e["path"])
            else:
                local = hf_hub_download(args.repo, e["path"], repo_type="dataset", local_dir=tmp)
                downloaded += 1
                if sha256(Path(local)) != e["sha256"]:
                    failures.append(e["path"])
    print(f"Hub matches manifest for {len(entries) - len(failures)} of {len(entries)} files "
          f"({downloaded} small non-LFS files downloaded and hashed)")
    for f in failures[:20]:
        print("MISSING OR DIFFERENT:", f)
    if failures:
        sys.exit(1)


def cmd_publish_card(args):
    """Upload the private-store card as the repository README (the repository must stay private)."""
    hub = api()
    if not getattr(hub.repo_info(args.repo, repo_type="dataset"), "private", False):
        sys.exit(f"{args.repo} is not private; refusing to upload")
    hub.upload_file(path_or_fileobj=str(ROOT / args.card), path_in_repo="README.md", repo_id=args.repo,
                    repo_type="dataset", commit_message="Describe the private store")
    print(f"uploaded {args.card} as README.md")


def cmd_free_local(args):
    records, failures = verify(args.repo)
    if not records:
        sys.exit("no local files to remove; the manifest is left unchanged")
    if failures:
        sys.exit(f"{len(failures)} files not verified; nothing removed")
    freed = 0
    for rec in records:
        p = ROOT / rec["path"]
        freed += p.stat().st_size
        p.unlink()
    MANIFEST.write_text(json.dumps({"repo": args.repo, "repo_type": "dataset", "private": True,
                                    "restore": f"python experiments/2026-10-06-research-program/hf_host.py restore --repo {args.repo}",
                                    "sets": SETS, "files": records}, indent=2) + "\n", encoding="utf-8")
    print(f"removed {len(records)} verified local files, {freed / 1e9:.2f} GB; manifest {MANIFEST.relative_to(ROOT)}")


def cmd_backup_files(args):
    """Upload large project-generated files that Git cannot hold, verify them, and keep the local copies."""
    hub = api()
    info = hub.repo_info(args.repo, repo_type="dataset")
    if not getattr(info, "private", False):
        sys.exit(f"{args.repo} is not private; refusing to upload")
    records = []
    for name, rel in BACKUP_FILES.items():
        path = ROOT / rel
        local_sha = sha256(path)
        parent = str(Path(rel).parent.as_posix())
        remote = remote_index(hub, args.repo, parent).get(rel) if hub.file_exists(args.repo, rel, repo_type="dataset") else None
        if not (remote and remote["size"] == path.stat().st_size and remote["sha256"] == local_sha):
            hub.upload_file(path_or_fileobj=str(path), path_in_repo=rel, repo_id=args.repo, repo_type="dataset",
                            commit_message=f"Back up {name}")
            remote = remote_index(hub, args.repo, parent).get(rel)
        ok = bool(remote) and remote["size"] == path.stat().st_size and remote["sha256"] in (None, local_sha)
        records.append({"set": name, "path": rel, "bytes": path.stat().st_size, "sha256": local_sha, "verified": ok})
        print(("verified " if ok else "NOT VERIFIED ") + rel)
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.exists() else {"repo": args.repo, "files": []}
    manifest["backed_up_files_kept_locally"] = records
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


def cmd_restore(args):
    from huggingface_hub import snapshot_download
    patterns = [spec["path"] + "/**" for spec in SETS.values()]
    snapshot_download(args.repo, repo_type="dataset", local_dir=str(ROOT), allow_patterns=patterns)
    print("restored", ", ".join(patterns))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("plan")
    for name in ("upload", "verify", "verify-remote", "free-local", "restore", "backup-files", "publish-card"):
        p = sub.add_parser(name)
        p.add_argument("--repo", required=True, help="NAMESPACE/NAME of the private dataset repository")
        if name == "publish-card":
            p.add_argument("--card", default="experiments/2026-10-08-hf-public-release/private-store/README.md",
                           help="card path relative to the repository root")
    args = parser.parse_args()
    {"plan": cmd_plan, "upload": cmd_upload, "verify": cmd_verify, "verify-remote": cmd_verify_remote,
     "free-local": cmd_free_local, "restore": cmd_restore, "backup-files": cmd_backup_files,
     "publish-card": cmd_publish_card}[args.command](args)


if __name__ == "__main__":
    main()
