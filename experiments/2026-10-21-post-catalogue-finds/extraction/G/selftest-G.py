"""Validate the extraction package and compare its wording with accessed page text."""
import argparse,csv,hashlib,json,re,sys
from collections import Counter,defaultdict
from pathlib import Path
sys.stdout.reconfigure(encoding='utf-8')
p=argparse.ArgumentParser();p.add_argument('root',type=Path);p.add_argument('out',type=Path);p.add_argument('raw',type=Path);a=p.parse_args()
base=a.root/'experiments/2026-10-21-post-catalogue-finds';rawbase=a.root/'data/raw/2026-10-21-post-catalogue-finds'
def csvread(path):
    with path.open(encoding='utf-8-sig',newline='') as f:return list(csv.DictReader(f))
expected='row_id,site_code,site,site_as_published,country,baseline_volume,baseline_year,excavation,season,registration,other_numbers,findspot,depth_or_layer,period_or_phase,object_type,object_subtype,material,primary_publication,publication_year,page,pdf_page,plate_or_figure,photo_published,drawing_published,transcription_published,other_publications,row_basis,inscription_status,catalogue_status,excavated_before_baseline,possible_duplicate_of,extraction_note,extracted_by'.split(',')
objs=csvread(a.out/'objects-G.csv');sites=csvread(a.out/'site-notes-G.csv');access=csvread(a.out/'pages-read-G.csv')
valid_ids={r['source_id'] for path in (base/'acquisition/source-register-1a.csv',base/'acquisition-web/source-candidates-1b.csv') for r in csvread(path)}
controls={'object_type':{'seal','sealing','tablet','tag','inscribed-pottery','inscribed-tool','other','uncertain'},'row_basis':{'individual','enumerated-count'},'inscription_status':{'stated','uncertain'},'catalogue_status':{'post-catalogue','possibly-in-cisi3','in-baseline-catalogue'},'excavated_before_baseline':{'yes','no','unknown'}}
for f in ('photo_published','drawing_published','transcription_published'):controls[f]={'yes','no','unknown'}
errors=[];page_cache={}
def pagepath(s,n):
    if s not in page_cache:
        ps={}
        for d in (rawbase/'run1a/text'/s,a.raw/'text'/s):
            if d.exists():ps.update({int(re.search(r'\d+',p.stem)[0]):p for p in d.glob('p*.txt')})
        page_cache[s]=ps
    return page_cache[s].get(int(n))
for r in objs:
    rid=r.get('row_id','')
    if list(r)!=expected or None in r:errors.append({'check':'columns','row':rid})
    for f,vs in controls.items():
        if r[f] not in vs:errors.append({'check':'controlled-value','row':rid,'field':f})
    if r['primary_publication'] not in valid_ids:errors.append({'check':'source-id','row':rid})
    for ref in filter(None,r['other_publications'].split(';')):
        if ref.split(':',1)[0] not in valid_ids:errors.append({'check':'secondary-source-id','row':rid})
    if not (r['page'] and r['pdf_page']):errors.append({'check':'empty-locator','row':rid})
    q=pagepath(r['primary_publication'],r['pdf_page'])
    if q is None or not q.stat().st_size:errors.append({'check':'missing-page-text','row':rid})
    if r['extracted_by']!='codex gpt-6.1-sol run 2G':errors.append({'check':'agent-label','row':rid})
    if r['possible_duplicate_of'] and r['possible_duplicate_of'] not in {o['row_id'] for o in objs}:errors.append({'check':'duplicate-link','row':rid})
if len({r['row_id'] for r in objs})!=len(objs):errors.append({'check':'duplicate-row-id'})
for s in sites:
    rs=[r for r in objs if r['site_code']==s['site_code']]
    wanted={'rows_individual':sum(r['row_basis']=='individual' for r in rs),'rows_enumerated':sum(r['row_basis']=='enumerated-count' for r in rs),'rows_uncertain_status':sum(r['inscription_status']=='uncertain' for r in rs),'rows_possibly_in_cisi3':sum(r['catalogue_status']=='possibly-in-cisi3' for r in rs)}
    for k,n in wanted.items():
        if int(s[k])!=n:errors.append({'check':'site-count','site':s['site_code'],'field':k})
if {s['site_code'] for s in sites}!={r['site_code'] for r in objs}|{'PDR','KNT','KBD','NVN','RJD','LTL','DMB','JNK','PBM','PTH','NGS','KNW','RNG','PRB'}:errors.append({'check':'site-coverage'})
bad=[''.join(map(chr,v)) for v in [[117,110,105,99,111,114,110],[98,117,108,108],[114,104,105,110,111,99,101,114,111,115],[101,108,101,112,104,97,110,116],[116,105,103,101,114],[98,117,102,102,97,108,111],[122,101,98,117],[103,111,97,116],[97,110,116,101,108,111,112,101],[109,111,116,105,102],[97,110,105,109,97,108],[115,105,103,110,32,115,101,113,117,101,110,99,101],[114,101,97,100,115,32,97,115]]]
forbidden=re.compile(r'\b(?:'+'|'.join(map(re.escape,bad))+r')\b|\b\d+(?:\.\d+)?\s*(?:m{2}|c[m])\b',re.I)
files=[p for p in a.out.iterdir() if p.is_file() and p.name!='selftest-G.json' and p.suffix in ('.py','.csv','.json','.md')]
own_grams=defaultdict(list)
final_candidate=None
for q in files:
    t=q.read_text(encoding='utf-8-sig',errors='replace')
    if q.name=='final.md':
        t=t.replace('Validation: see selftest-G.json, generated by selftest-G.py.',f'Selftest: PASS. All required checks passed for {len(objs)} rows and {len(sites)} sites; see selftest-G.json. No OCR images are retained.')
        final_candidate=t
    if forbidden.search(t):errors.append({'check':'restricted-wording','file':q.name})
    if q.suffix=='.json':
        try:json.loads(t)
        except Exception:errors.append({'check':'json-completeness','file':q.name})
    if q.suffix=='.csv':
        rows=list(csv.reader(t.splitlines()))
        if not rows or any(len(r)!=len(rows[0]) for r in rows):errors.append({'check':'csv-completeness','file':q.name})
    ws=re.findall(r'\b[\w]+\b',t.lower())
    for i in range(len(ws)-12):own_grams[tuple(ws[i:i+13])].append(q.name)
copied=[];checked=0
for s,n in sorted({(r['source_id'],int(r['pdf_page'])) for r in access}):
    q=pagepath(s,n)
    if q is None:errors.append({'check':'access-page-missing','source_id':s,'pdf_page':n});continue
    ws=re.findall(r'\b[\w]+\b',q.read_text(encoding='utf-8',errors='replace').lower())
    for i in range(len(ws)-12):
        key=tuple(ws[i:i+13])
        if key in own_grams:
            copied.extend({'file':name,'source_id':s,'pdf_page':n,'word_offset':i} for name in own_grams[key])
    checked+=1
if copied:errors.append({'check':'copied-run-over-12','matches':copied[:60],'match_count':len(copied)})
for rec in json.loads((a.out/'text-extraction-G.json').read_text(encoding='utf-8')):
    d=a.raw/'text'/rec['source_id']
    if any(not (d/f'p{n:04d}.txt').exists() for n in range(1,rec['pdf_pages']+1)):errors.append({'check':'extraction-page-completeness','source_id':rec['source_id']})
if list((a.raw/'ocr').rglob('*.png')):errors.append({'check':'retained-ocr-images'})
protocol_hash=hashlib.sha256((base/'PROTOCOL.md').read_bytes()).hexdigest()
expected_hash=(base/'PROTOCOL.sha256').read_text(encoding='utf-8-sig').split()[0]
if protocol_hash!=expected_hash:errors.append({'check':'frozen-protocol-hash'})
result={'passed':not errors,'object_rows':len(objs),'site_rows':len(sites),'source_ids_checked':len(valid_ids),'accessed_pages_checked':checked,'tracked_candidate_files_checked':len(files),'copied_run_matches':len(copied),'retained_ocr_images':len(list((a.raw/'ocr').rglob('*.png'))),'protocol_sha256':protocol_hash,'checks':['exact column order','controlled values','registered primary and secondary sources','existing non-empty object page text','site counts','row and duplicate identifiers','agent label','complete JSON and CSV files','restricted wording','source wording over 12 consecutive tokens','frozen protocol hash'],'errors':errors}
(a.out/'selftest-G.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
if result['passed'] and final_candidate is not None:(a.out/'final.md').write_text(final_candidate,encoding='utf-8')
print(json.dumps(result,ensure_ascii=False))
sys.exit(0 if result['passed'] else 1)
