async (page) => {
  const base = 'http://127.0.0.1:8766/experiments/2026-10-26-indus-living-atlas/';
  const raw = 'D:/projects/indus_valley_script/data/raw/2026-10-26-indus-living-atlas/qa/';
  const checks=[], errors=[], requests=[];
  const check=(name,passed,detail=null)=>checks.push({name,passed:!!passed,detail});
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('request',r=>requests.push(r.url()));
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'index.html');
  await page.waitForFunction(()=>window.indusAtlas?.getVisible().length>0);
  check('South Asia preserves 84 plotted and one unlocated entry',(await page.evaluate(()=>window.indusAtlas.getVisible().filter(r=>r.located).length))===84 && (await page.evaluate(()=>window.indusAtlas.getVisible().length))===85);
  await page.locator('#search').fill('Harappa');
  check('Search isolates Harappa',(await page.locator('.place').count())===1);
  await page.locator('.place').click();
  check('Harappa source panel exposes seven phases',(await page.locator('#detail-panel .phase').count())===7&&(await page.locator('#detail-panel').innerText()).includes('Kenoyer'));
  await page.keyboard.press('Escape');
  check('Escape closes place panel',await page.locator('#detail-panel').isHidden());
  await page.locator('#search').fill('');
  await page.locator('#extent').selectOption('all');
  check('All locations include all 115 entities and three unlocated',(await page.evaluate(()=>window.indusAtlas.getVisible().length))===115&&(await page.evaluate(()=>window.indusAtlas.getVisible().filter(r=>!r.located).length))===3);
  await page.locator('#country').selectOption('Iraq');
  check('Country filter finds the Ur reference',(await page.evaluate(()=>window.indusAtlas.getVisible().some(r=>r.id==='ur'))));
  await page.locator('#country').selectOption('all');
  await page.locator('.more-filters > summary').click();
  await page.locator('#quality').selectOption('flagged');
  const flagged=await page.evaluate(()=>window.indusAtlas.getVisible().map(r=>r.id));
  check('Location warnings expose the three inherited problem cases',['allahdino','nindowari','tell-abraq'].every(id=>flagged.includes(id)),flagged);
  await page.locator('#quality').selectOption('all');
  await page.locator('.more-filters > summary').click();
  await page.locator('#extent').selectOption('south-asia');
  await page.locator('button[data-period=late]').click();
  const late=await page.evaluate(()=>window.indusAtlas.getVisible().map(r=>r.id));
  check('Late window excludes Mature-only Mohenjo-daro and includes Harappa',!late.includes('mohenjo-daro')&&late.includes('harappa'),late.length);
  check('Shared boundaries, point dates and single dates retain declared semantics',await page.evaluate(()=>!window.indusAtlas.overlaps({start_bce:2600,end_bce:1900},1900,1300)&&window.indusAtlas.overlaps({start_bce:1400,end_bce:1400},1900,1300)&&window.indusAtlas.overlaps({start_bce:2600,end_bce:1900},1900,1900)));
  await page.locator('#single-year').check();
  await page.locator('#year').focus();
  await page.keyboard.press('Home');
  check('Keyboard date slider updates its accessible output',(await page.evaluate(()=>window.indusAtlas.getState().year))===1000&&(await page.locator('#year-label').innerText()).includes('1000'));
  await page.locator('button[data-layer=towns]').click();
  check('Town candidates number sixteen and exclude abandoned comparisons',await page.evaluate(()=>window.indusAtlas.getVisible().length===16&&!window.indusAtlas.getVisible().some(r=>['LT-17','LT-18'].includes(r.id))));
  check('Town mode disables archaeological date control',await page.locator('#single-year').isDisabled());
  await page.locator('#towns-open').click();
  check('Evidence table keeps all eighteen cases',(await page.locator('#town-table tbody tr').count())===18);
  await page.locator('#town-table button[data-town="town:LT-04"]').click();
  check('Table selects Harappa town and its occupation gap',(await page.locator('#detail-panel').innerText()).includes('1300')&&(await page.locator('#detail-panel').innerText()).includes('Harappa'));
  await page.keyboard.press('Escape');
  await page.locator('button[data-layer=both]').click();
  await page.locator('button[data-period=all]').click();
  check('Compare mode keeps site and modern place identities separate',await page.evaluate(()=>window.indusAtlas.getVisible().length===101&&window.indusAtlas.getVisible().filter(r=>r.layer==='town').length===16));
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#export').click()]);
  await download.saveAs(raw+'filtered-places-v1.geojson');
  check('GeoJSON export downloads',download.suggestedFilename()==='indus-atlas-places.geojson');
  await page.locator('button[data-layer=sites]').click();
  await page.locator('#about-open').click();
  check('Evidence guide opens',await page.locator('#about-dialog').isVisible());
  await page.keyboard.press('Escape');
  await page.screenshot({path:raw+'map-desktop-final-v1.png'});
  check('Core map issues no remote asset requests',requests.every(url=>url.startsWith('http://127.0.0.1:8766/')),requests);
  await page.context().setOffline(true);
  await page.locator('button[data-layer=towns]').click();
  check('Town switch works with browser network offline',(await page.evaluate(()=>window.indusAtlas.getVisible().length))===16);
  await page.context().setOffline(false);
  await page.setViewportSize({width:390,height:844});
  check('Phone layout has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  check('Continuity link remains available on phone',await page.locator('nav a[href="research.html#continuity"]').isVisible());
  await page.screenshot({path:raw+'map-mobile-final-v1.png',fullPage:true});
  await page.goto(base+'research.html');
  check('Readable research page contains both reports',await page.locator('#continuity').isVisible()&&await page.locator('#living-towns').count()===1);
  check('Research reader has no phone overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:raw+'research-desktop-final-v1.png'});
  await page.goto(base+'reconstruction/index.html#model=dholavira&view=plan');
  await page.waitForFunction(()=>window.INDUS3D?.getState().model==='dholavira');
  check('Map-to-model entry preserves city and Plan fragment',await page.evaluate(()=>window.INDUS3D.getState().view==='plan'));
  const atlasLink=page.getByRole('link',{name:'← Living atlas',exact:true});
  check('Model returns to atlas',await atlasLink.count()===1);
  await atlasLink.click();
  check('Model return link reaches the main atlas',page.url()===base+'index.html');
  check('No browser script errors',errors.length===0,errors);
  return {schema_version:'1.0',tool:'Playwright CLI, Chromium',map_snapshot:'mapping/run-v2',checks,errors,passed:checks.every(r=>r.passed)};
}
