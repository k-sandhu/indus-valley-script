async (page) => {
  const raw='D:/projects/indus_valley_script/data/raw/2026-10-26-indus-living-atlas/reconstruction/';
  const base='http://127.0.0.1:8766/experiments/2026-10-26-indus-living-atlas/reconstruction/run-v5/index.html';
  const checks=[],models=[],errors=[];
  const check=(name,pass,detail=null)=>checks.push({name,passed:!!pass,detail});
  page.on('pageerror',e=>errors.push(String(e)));
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base);
  const ids=['mohenjo-daro','dholavira','great-bath','dholavira-reservoir','dholavira-gate','pillared-hall','lothal-basin'];
  for (const id of ids) {
    await page.getByLabel('Choose a city or building').selectOption(id);
    await page.waitForFunction(id=>window.INDUS3D?.getState().model===id&&window.INDUS3D.getState().faces>0,id);
    const state=await page.evaluate(()=>window.INDUS3D.getState());
    const pixels=await page.evaluate(()=>{const c=document.getElementById('mesh-canvas'),g=c.getContext('webgl'),a=new Uint8Array(c.width*c.height*4);g.readPixels(0,0,c.width,c.height,g.RGBA,g.UNSIGNED_BYTE,a);let n=0;for(let i=3;i<a.length;i+=4)if(a[i])n++;return n;});
    models.push({id,state,opaque_pixels:pixels,screenshot:raw+id+'-v5.png'});
    check(id+' WebGL and nonblank model',state.renderer==='WebGL depth buffer'&&state.faces>10&&pixels>2000,{pixels,faces:state.faces});
    check(id+' feature card populated',(await page.getByRole('heading',{level:3}).innerText()).length>0);
    await page.screenshot({path:raw+id+'-v5.png'});
  }
  await page.getByLabel('Choose a city or building').selectOption('great-bath');
  await page.getByRole('button',{name:'Plan',exact:true}).click();
  let state=await page.evaluate(()=>window.INDUS3D.getState());
  check('Plan mode and fragment',state.view==='plan'&&Math.abs(state.pitch-Math.PI/2)<1e-9&&page.url().includes('view=plan'));
  const surface=await page.locator('#canvas').boundingBox();
  const centre=await page.evaluate(()=>window.INDUS3D.project([0,0,.03]));
  await page.mouse.click(surface.x+centre[0],surface.y+centre[1]);
  state=await page.evaluate(()=>window.INDUS3D.getState());
  check('surface picking chooses basin',state.selected==='basin',state.selected);
  await page.getByRole('button',{name:'Opposed stairs and ledges',exact:true}).click();
  check('accessible feature list selection',(await page.getByRole('heading',{level:3}).innerText())==='Opposed stairs and ledges');
  const beforeFocus=await page.evaluate(()=>window.INDUS3D.getState().scale);
  await page.getByRole('button',{name:'Focus ↗',exact:true}).click();
  check('feature focus increases detail',(await page.evaluate(()=>window.INDUS3D.getState().scale))>beforeFocus);
  await page.getByRole('button',{name:'3D orbit',exact:true}).click();
  await page.locator('#canvas').focus();
  const before=await page.evaluate(()=>window.INDUS3D.getState());
  await page.keyboard.press('ArrowRight');
  check('keyboard orbit changes yaw',(await page.evaluate(()=>window.INDUS3D.getState().yaw))!==before.yaw);
  await page.keyboard.press('p');
  check('keyboard Plan shortcut',(await page.evaluate(()=>window.INDUS3D.getState().view))==='plan');
  const beforeZoom=await page.evaluate(()=>window.INDUS3D.getState().scale);
  await page.getByRole('button',{name:'Zoom in',exact:true}).click();
  check('zoom control',(await page.evaluate(()=>window.INDUS3D.getState().scale))>beforeZoom);
  await page.getByLabel('Cutaway',{exact:true}).check();
  await page.getByLabel('Possible roofs',{exact:true}).check();
  await page.getByLabel('Display water',{exact:true}).check();
  await page.getByRole('button',{name:'Evidence colours',exact:true}).click();
  state=await page.evaluate(()=>window.INDUS3D.getState());
  check('layer switches',state.layers.cut&&state.layers.roofs&&state.layers.water);
  await page.getByLabel('Assumed superstructure height percent').focus();
  await page.keyboard.press('End');
  check('height sensitivity slider',(await page.evaluate(()=>window.INDUS3D.getState().heightFactor))===1.6);
  const publishedDepths=await page.evaluate(()=>{const s=window.INDUS3D.data.scenes.find(s=>s.id==='great-bath');return s.meshes.filter(m=>m.feature==='basin').every(m=>!m.variable);});
  check('height slider keeps published basin fixed',publishedDepths);
  await page.getByRole('button',{name:'Reset view',exact:true}).click();
  await page.getByText('Export the geometry',{exact:true}).click();
  let [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Download OBJ',exact:true}).click()]);
  await download.saveAs(raw+'browser-great-bath-v5.obj');check('OBJ download',download.suggestedFilename()==='great-bath.obj');
  [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Download scene JSON',exact:true}).click()]);
  await download.saveAs(raw+'browser-great-bath-v5.json');check('JSON download',download.suggestedFilename()==='great-bath.json');
  await page.context().setOffline(true);
  await page.getByLabel('Choose a city or building').selectOption('dholavira-reservoir');
  check('model switch with network offline',(await page.evaluate(()=>window.INDUS3D.getState().model))==='dholavira-reservoir');
  await page.context().setOffline(false);
  await page.goto(base+'#model=dholavira&view=plan');
  check('direct city Plan fragment',(await page.evaluate(()=>window.INDUS3D.getState().model))==='dholavira'&&(await page.evaluate(()=>window.INDUS3D.getState().view))==='plan');
  await page.screenshot({path:raw+'dholavira-plan-v5.png'});
  await page.setViewportSize({width:390,height:844});
  await page.getByLabel('Choose a city or building').selectOption('great-bath');
  await page.screenshot({path:raw+'mobile-bath-v5.png',fullPage:true});
  const mobile=await page.evaluate(()=>({viewport:innerWidth,body:document.documentElement.scrollWidth,canvas:document.getElementById('canvas').getBoundingClientRect().toJSON(),state:window.INDUS3D.getState()}));
  check('mobile layout has no horizontal overflow',mobile.body===mobile.viewport,mobile);
  const sources=await page.locator('#feature-body a[target="_blank"]').count();check('source link on mobile',sources>0);
  await page.getByRole('button',{name:'3D orbit',exact:true}).click();
  await page.locator('#canvas').focus();
  const box=await page.locator('#canvas').boundingBox();
  const yaw=await page.evaluate(()=>window.INDUS3D.getState().yaw);
  await page.mouse.move(box.x+100,box.y+240);await page.mouse.down();await page.mouse.move(box.x+150,box.y+260,{steps:8});await page.mouse.up();
  check('drag orbit on narrow viewport',(await page.evaluate(()=>window.INDUS3D.getState().yaw))!==yaw);
  check('no browser script errors',errors.length===0,errors);
  await page.setViewportSize({width:1440,height:1000});
  return {schema_version:'1.0',run:'run-v5',tool:'Playwright CLI, Chromium',checks,models,mobile,errors,passed:checks.every(c=>c.passed)};
}
